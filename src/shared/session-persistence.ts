// Rebuilds one structured mention segment, dropping malformed entries so the bubble stays renderable.
const sanitizeMessagePart = (part: unknown): MessagePart | undefined => {
  if (!isRecord(part)) return undefined

  switch (asString(part.type)) {
    case 'text': {
      const text = asString(part.text)

      return text !== undefined ? { type: 'text', text } : undefined
    }
    case 'skill': {
      const id = asString(part.id)
      const name = asString(part.name)

      return id && name ? { type: 'skill', id, name } : undefined
    }
    case 'session': {
      const sessionId = asString(part.sessionId)
      const title = asString(part.title)

      return sessionId && title ? { type: 'session', sessionId, title } : undefined
    }
    case 'artifact': {
      const id = asString(part.id)
      const name = asString(part.name)
      const source = asString(part.source)

      if (!id || !name) return undefined

      const mimeType = asString(part.mimeType)
      if (source === 'linked-folder') {
        const rootId = asString(part.rootId)
        const relativePath = asString(part.relativePath)
        if (!rootId || !relativePath) return undefined

        return {
          type: 'artifact',
          id,
          name,
          source,
          rootId,
          relativePath,
          ...(mimeType ? { mimeType } : {})
        }
      }

      const path = asString(part.path)
      if (!path || (source !== 'upload' && source !== 'artifact')) return undefined

      const sanitized: MessagePart = { type: 'artifact', id, name, path, source }
      const versionId = asString(part.versionId)
      const sourceFileId = asString(part.sourceFileId)

      return {
        ...sanitized,
        ...(mimeType ? { mimeType } : {}),
        ...(sourceFileId ? { sourceFileId } : {}),
        ...(versionId ? { versionId } : {})
      }
    }
    default:
      return undefined
  }
}

export const sanitizeSessionReferences = (value: unknown): SessionReference[] => {
  if (!Array.isArray(value)) return []
  const references: SessionReference[] = []
  for (const candidate of value) {
    if (references.length >= MAX_SESSION_REFERENCES_PER_MESSAGE) break
    const part = sanitizeMessagePart(candidate)
    if (
      part?.type !== 'session' ||
      part.sessionId.length > MAX_SESSION_REFERENCE_ID_LENGTH ||
      part.title.length > MAX_SESSION_REFERENCE_TITLE_LENGTH ||
      references.some((reference) => reference.sessionId === part.sessionId)
    ) {
      continue
    }
    references.push({ type: 'session', sessionId: part.sessionId, title: part.title })
  }
  return references
}

// Revalidates embedded message images before writing or restoring a session file. The count and
// aggregate byte budget prevent many individually valid chunks from growing one message without bound.
export const sanitizeMessageImages = (value: unknown): PersistedMessageImage[] | undefined => {
  if (!Array.isArray(value)) return undefined

  const images: PersistedMessageImage[] = []
  let totalBytes = 0

  for (const candidate of value) {
    if (images.length >= MAX_ACP_MESSAGE_IMAGES_PER_MESSAGE || !isRecord(candidate)) break

    const id = asString(candidate.id)
    const image = sanitizeAcpMessageImage(candidate)

    if (!id || !image) continue
    if (totalBytes + image.byteLength > MAX_ACP_MESSAGE_IMAGE_BYTES_PER_MESSAGE) break

    images.push({ id, ...image })
    totalBytes += image.byteLength
  }

  return images.length > 0 ? images : undefined
}

// Applies the image boundary immediately before repository serialization without changing runtime
// status fields (running sessions must remain restorable as interrupted sessions after a restart).
export function sanitizeSessionMessageImages(
  session: MaterializedPersistedChatSession
): MaterializedPersistedChatSession
export function sanitizeSessionMessageImages(session: PersistedChatSession): PersistedChatSession
export function sanitizeSessionMessageImages(session: PersistedChatSession): PersistedChatSession {
  const sanitizeMessages = <Message extends PersistedChatMessage>(
    messages: readonly Message[]
  ): Message[] => {
    let totalBytes = 0
    return messages.map((message) => {
      const images = (sanitizeMessageImages(message.images) ?? []).filter((image) => {
        if (totalBytes + image.byteLength > MAX_ACP_SESSION_IMAGE_BYTES) return false
        totalBytes += image.byteLength
        return true
      })
      const annotations = (message.annotations ?? []).filter((annotation) => {
        if (annotation.kind !== 'pdf' || annotation.selector.kind !== 'region') return true
        if (totalBytes + annotation.selector.image.byteLength > MAX_ACP_SESSION_IMAGE_BYTES) {
          return false
        }
        totalBytes += annotation.selector.image.byteLength
        return true
      })
      return {
        ...message,
        annotations: annotations.length > 0 ? annotations : undefined,
        images: images.length > 0 ? images : undefined
      }
    })
  }

  if (!session.conversationGraph) {
    return { ...session, messages: sanitizeMessages(session.messages) }
  }

  // The graph is canonical and includes inactive Branches. Sanitize it once under one aggregate
  // budget, then rebuild the active compatibility projection so duplicate active messages are not
  // counted twice and hidden Branches cannot bypass the on-disk image boundary.
  const conversationGraph = {
    ...session.conversationGraph,
    messages: sanitizeMessages(session.conversationGraph.messages)
  }
  return {
    ...session,
    conversationGraph,
    messages: resolveActiveConversationMessages(conversationGraph).map(projectConversationMessage)
  }
}

// Applies the path-free upload boundary immediately before repository serialization without
// normalizing run/session state. This preserves crash-restoration semantics while ensuring legacy
// renderer paths and checksum aliases can never leak into newly written Session JSON.
export const sanitizeSessionUploadedAttachments = (
  session: PersistedChatSession
): PersistedChatSession => {
  const sanitizeUploads = <Message extends PersistedChatMessage>(message: Message): Message => {
    const uploads = (message.uploads ?? [])
      .map((upload) => sanitizeUploadedAttachment(upload))
      .filter((upload): upload is PersistedUploadedAttachment => !!upload)
    return { ...message, uploads: uploads.length > 0 ? uploads : undefined }
  }
  return {
    ...session,
    messages: session.messages.map(sanitizeUploads),
    ...(session.conversationGraph
      ? {
          conversationGraph: {
            ...session.conversationGraph,
            messages: session.conversationGraph.messages.map(sanitizeUploads)
          }
        }
      : {})
  }
}

const sanitizeStructuredJson = (
  value: unknown,
  limits: { bytes: number; nodes: number; depth: number; properties: number; items: number }
): unknown | undefined => {
  try {
    let nodes = 0
    const inspect = (candidate: unknown, depth: number): boolean => {
      nodes += 1
      if (nodes > limits.nodes || depth > limits.depth) return false
      if (candidate === null || typeof candidate === 'string' || typeof candidate === 'boolean')
        return true
      if (typeof candidate === 'number')
        return Number.isFinite(candidate) && !Object.is(candidate, -0)
      if (Array.isArray(candidate)) {
        return (
          candidate.length <= limits.items &&
          Object.keys(candidate).length === candidate.length &&
          candidate.every((item) => inspect(item, depth + 1))
        )
      }
      if (!isRecord(candidate) || Object.getPrototypeOf(candidate) !== Object.prototype)
        return false
      const keys = Object.keys(candidate)
      return (
        keys.length <= limits.properties &&
        !keys.some((key) => key === '__proto__' || key === 'prototype' || key === 'constructor') &&
        keys.every((key) => inspect(candidate[key], depth + 1))
      )
    }
    if (!inspect(value, 0)) return undefined
    const serialized = JSON.stringify(value)
    if (serialized === undefined || Buffer.byteLength(serialized, 'utf8') > limits.bytes)
      return undefined
    return JSON.parse(serialized) as unknown
  } catch {
    return undefined
  }
}

const sanitizeStructuredOutputEvidence = (
  value: unknown
): PersistedChatMessage['structuredOutputEvidence'] | undefined => {
  if (
    !isRecord(value) ||
    !hasOnlyFields(value, ['attemptId', 'dialect', 'profile', 'schemaDigest', 'schema', 'accepted'])
  )
    return undefined
  const attemptId = asString(value.attemptId)
  const schemaDigest = asString(value.schemaDigest)
  if (
    !attemptId ||
    value.dialect !== '2020-12' ||
    value.profile !== 'ajv-8-draft-2020-12-v1' ||
    !schemaDigest ||
    !/^[a-f0-9]{64}$/.test(schemaDigest)
  )
    return undefined
  const schema = sanitizeStructuredJson(value.schema, {
    bytes: 64 * 1024,
    nodes: 1_000,
    depth: 32,
    properties: 128,
    items: 128
  })
  if (schema === undefined || (typeof schema !== 'boolean' && !isRecord(schema))) return undefined
  let accepted: { value: unknown; acceptedAt: number } | undefined
  if (value.accepted !== undefined) {
    if (!isRecord(value.accepted) || !hasOnlyFields(value.accepted, ['value', 'acceptedAt']))
      return undefined
    const acceptedAt = asNumber(value.accepted.acceptedAt)
    const acceptedValue = sanitizeStructuredJson(value.accepted.value, {
      bytes: 256 * 1024,
      nodes: 5_000,
      depth: 32,
      properties: 256,
      items: 1_000
    })
    if (acceptedAt === undefined || acceptedAt < 0 || acceptedValue === undefined) return undefined
    accepted = { value: acceptedValue, acceptedAt }
  }
  return {
    attemptId,
    dialect: '2020-12',
    profile: 'ajv-8-draft-2020-12-v1',
    schemaDigest,
    schema,
    ...(accepted ? { accepted } : {})
  }
}

// Rebuilds a message from durable UI fields and strips unknown renderer payload.
const sanitizeMessage = (
  message: unknown,
  options: { preserveLegacyUploadPaths?: boolean } = {}
): PersistedChatMessage | undefined => {
  if (!isRecord(message)) return undefined

  const id = asString(message.id)
  const role = asMessageRole(message.role)
  const content = asString(message.content)

  if (!id || !role || content === undefined) return undefined

  const sanitized: PersistedChatMessage = {
    id,
    role,
    content,
    status: asMessageStatus(message.status),
    eventIds: asStringArray(message.eventIds),
    createdAt: asNumber(message.createdAt) ?? 0,
    updatedAt: asNumber(message.updatedAt) ?? 0
  }
  const attribution = sanitizeMessageAttribution(message.attribution)
  const presentation =
    role === 'user' ? sanitizeMessagePresentation(message.presentation) : undefined
  const streamId = asString(message.streamId)
  const responseToMessageId = asString(message.responseToMessageId)
  const artifactIds = asStringArray(message.artifactIds)
  const delegatedTask = asString(message.delegatedTask)
  const delegatedInputVersionIds = asStringArray(message.delegatedInputVersionIds)
  const explicitDelegatedCallerSource = sanitizeDelegatedCallerSource(message.delegatedCallerSource)
  const legacyCallerMessageId = asString(message.delegatedCallerMessageId)
  const legacyToolInvocationId = asString(message.delegatedToolInvocationId)
  const delegatedCallerSource =
    explicitDelegatedCallerSource ??
    (legacyCallerMessageId && legacyToolInvocationId
      ? { rootMessageId: legacyCallerMessageId, toolInvocationId: legacyToolInvocationId }
      : undefined)
  const uploads = Array.isArray(message.uploads)
    ? message.uploads
        .map((attachment) =>
          sanitizeUploadedAttachment(attachment, {
            preserveLegacyPath: options.preserveLegacyUploadPaths
          })
        )
        .filter((item): item is PersistedUploadedAttachment => !!item)
    : []
  const parts = Array.isArray(message.parts)
    ? message.parts.map(sanitizeMessagePart).filter((item): item is MessagePart => !!item)
    : []
  const annotations = role === 'user' ? sanitizeAnnotations(message.annotations) : []
  const pdfContext =
    role === 'user' ? sanitizeMessagePdfContextSnapshot(message.pdfContext) : undefined
  const images = sanitizeMessageImages(message.images)
  const turnUsage = role === 'agent' ? sanitizeAcpTurnTokenUsage(message.turnUsage) : undefined
  const candidateModelCallUsage =
    role === 'agent' && turnUsage?.turnCount && Array.isArray(message.modelCallUsage)
      ? message.modelCallUsage.map(sanitizeAcpModelCallUsage)
      : []
  const modelCallUsage =
    candidateModelCallUsage.length === turnUsage?.turnCount &&
    candidateModelCallUsage.every(
      (call, index): call is AcpModelCallUsage => call !== undefined && call.index === index
    ) &&
    new Set(candidateModelCallUsage.map((call) => call?.id)).size === candidateModelCallUsage.length
      ? candidateModelCallUsage
      : []
  const modelCallTotals = modelCallUsage.reduce(
    (totals, call) => ({
      inputTokens: totals.inputTokens + call.inputTokens,
      cacheTokens: totals.cacheTokens + call.cacheTokens,
      outputTokens: totals.outputTokens + call.outputTokens
    }),
    { inputTokens: 0, cacheTokens: 0, outputTokens: 0 }
  )
  const hasMatchingModelCallTotals =
    !!turnUsage &&
    Number.isSafeInteger(modelCallTotals.inputTokens) &&
    Number.isSafeInteger(modelCallTotals.cacheTokens) &&
    Number.isSafeInteger(modelCallTotals.outputTokens) &&
    modelCallTotals.inputTokens === turnUsage.inputTokens &&
    modelCallTotals.cacheTokens === turnUsage.cacheTokens &&
    modelCallTotals.outputTokens === turnUsage.outputTokens
  const turnUsageUnavailable =
    role === 'agent' && !turnUsage && message.turnUsageUnavailable === true
  const contextWindowSamples =
    role === 'user' && Array.isArray(message.contextWindowSamples)
      ? message.contextWindowSamples
          .map(sanitizeAcpContextWindowSample)
          .filter((sample): sample is AcpContextWindowSample => !!sample)
      : []
  const completedAt = asNumber(message.completedAt)
  const failedAt = asNumber(message.failedAt)
  const structuredOutputEvidence = sanitizeStructuredOutputEvidence(
    message.structuredOutputEvidence
  )

  if (streamId) sanitized.streamId = streamId
  if (attribution) sanitized.attribution = attribution
  if (presentation) sanitized.presentation = presentation
  // Older application-routed user Messages could persist their own id as the response target.
  // The edge carries no information, so canonicalize that known legacy shape on every read path.
  if (responseToMessageId && (role !== 'user' || responseToMessageId !== id)) {
    sanitized.responseToMessageId = responseToMessageId
  }
  if (artifactIds.length > 0) sanitized.artifactIds = artifactIds
  if (delegatedTask) sanitized.delegatedTask = delegatedTask
  if (delegatedInputVersionIds.length > 0) {
    sanitized.delegatedInputVersionIds = delegatedInputVersionIds
  }
  if (delegatedCallerSource) sanitized.delegatedCallerSource = delegatedCallerSource
  if (uploads.length > 0) sanitized.uploads = uploads
  if (parts.length > 0) sanitized.parts = parts
  if (annotations.length > 0) sanitized.annotations = annotations
  if (pdfContext) sanitized.pdfContext = pdfContext
  if (
    role === 'user' &&
    (message.turnIntent === 'plan-first' || message.turnIntent === 'save-as-skill')
  ) {
    sanitized.turnIntent = message.turnIntent
  }
  if (
    role === 'user' &&
    isRecord(message.relayedFrom) &&
    message.relayedFrom.kind === 'side-chat' &&
    message.relayedFrom.direction === 'to-main'
  ) {
    sanitized.relayedFrom = { kind: 'side-chat', direction: 'to-main' }
  }
  if (images) sanitized.images = images
  if (turnUsage) sanitized.turnUsage = turnUsage
  if (hasMatchingModelCallTotals) sanitized.modelCallUsage = modelCallUsage
  if (contextWindowSamples.length > 0) sanitized.contextWindowSamples = contextWindowSamples
  if (turnUsageUnavailable) sanitized.turnUsageUnavailable = true
  if (structuredOutputEvidence) sanitized.structuredOutputEvidence = structuredOutputEvidence
  if (
    message.structuredOutputEvidenceInvalid === true ||
    (message.structuredOutputEvidence !== undefined && !structuredOutputEvidence)
  ) {
    sanitized.structuredOutputEvidenceInvalid = true
  }
  if (role === 'user' && message.interrupted === true) sanitized.interrupted = true
  if (role === 'user') {
    const agentTarget = sanitizeMessageAgentTarget(message.agentTarget)
    if (agentTarget) sanitized.agentTarget = agentTarget
  }
  if (role === 'agent' && sanitized.status === 'complete') {
    sanitized.completedAt = completedAt ?? sanitized.updatedAt
  }
  if (role === 'agent' && sanitized.status === 'error') {
    sanitized.failedAt = failedAt ?? sanitized.updatedAt
  }

  return sanitized
}

const sanitizeConversationGraph = (
  value: unknown,
  options: { preserveLegacyUploadPaths?: boolean; preserveRuntimeState?: boolean } = {}
): PersistedConversationGraph | undefined => {
  if (!isRecord(value) || value.schemaVersion !== 1) return undefined
  const rootFrameId = asString(value.rootFrameId)
  const activeFrameId = asString(value.activeFrameId)
  if (!rootFrameId || !activeFrameId) return undefined

  const frames = Array.isArray(value.frames)
    ? value.frames.flatMap((candidate): PersistedAgentFrame[] => {
        if (!isRecord(candidate)) return []
        const id = asString(candidate.id)
        const activeBranchId = asString(candidate.activeBranchId)
        const kind = asString(candidate.kind) as PersistedAgentFrame['kind'] | undefined
        const originBindingState = asString(candidate.originBindingState) as
          PersistedAgentFrame['originBindingState'] | undefined
        const status = asString(candidate.status) as PersistedAgentFrame['status'] | undefined
        const createdAt = asNumber(candidate.createdAt)
        if (
          !id ||
          !activeBranchId ||
          !kind ||
          !['root', 'reviewer', 'delegate', 'compatibility'].includes(kind) ||
          !originBindingState ||
          !['root', 'validated', 'legacy-unavailable'].includes(originBindingState) ||
          !status ||
          !['running', 'completed', 'cancelled', 'error'].includes(status) ||
          createdAt === undefined
        ) {
          return []
        }
        return [
          {
            id,
            activeBranchId,
            kind,
            originBindingState,
            status,
            createdAt,
            ...(asString(candidate.parentFrameId)
              ? { parentFrameId: asString(candidate.parentFrameId) }
              : {}),
            ...(asString(candidate.originMessageId)
              ? { originMessageId: asString(candidate.originMessageId) }
              : {}),
            ...(asString(candidate.agentName) ? { agentName: asString(candidate.agentName) } : {}),
            ...(asString(candidate.delegateName)
              ? { delegateName: asString(candidate.delegateName) }
              : {}),
            ...(asString(candidate.linkedReviewId)
              ? { linkedReviewId: asString(candidate.linkedReviewId) }
              : {}),
            ...(asNumber(candidate.completedAt) !== undefined
              ? { completedAt: asNumber(candidate.completedAt) }
              : {})
          }
        ]
      })
    : []
  const branches = Array.isArray(value.branches)
    ? value.branches.flatMap((candidate): PersistedMessageBranch[] => {
        if (!isRecord(candidate)) return []
        const id = asString(candidate.id)
        const agentFrameId = asString(candidate.agentFrameId)
        const createdAt = asNumber(candidate.createdAt)
        const updatedAt = asNumber(candidate.updatedAt)
        if (!id || !agentFrameId || createdAt === undefined || updatedAt === undefined) return []
        return [
          {
            id,
            agentFrameId,
            createdAt,
            updatedAt,
            ...(asString(candidate.parentBranchId)
              ? { parentBranchId: asString(candidate.parentBranchId) }
              : {}),
            ...(asString(candidate.forkMessageId)
              ? { forkMessageId: asString(candidate.forkMessageId) }
              : {}),
            ...(asString(candidate.forkActivityId)
              ? { forkActivityId: asString(candidate.forkActivityId) }
              : {}),
            ...(asString(candidate.supersededMessageId)
              ? { supersededMessageId: asString(candidate.supersededMessageId) }
              : {}),
            ...(asString(candidate.headMessageId)
              ? { headMessageId: asString(candidate.headMessageId) }
              : {})
          }
        ]
      })
    : []
  const messages = Array.isArray(value.messages)
    ? value.messages.flatMap((candidate): PersistedMessageNode[] => {
        if (!isRecord(candidate)) return []
        const message = sanitizeMessage(candidate, options)
        const agentFrameId = asString(candidate.agentFrameId)
        const introducedOnBranchId = asString(candidate.introducedOnBranchId)
        if (!message || !agentFrameId || !introducedOnBranchId) return []
        return [
          {
            ...(options.preserveRuntimeState ? message : normalizeMessageAfterRestore(message)),
            agentFrameId,
            introducedOnBranchId,
            ...(asString(candidate.parentMessageId)
              ? { parentMessageId: asString(candidate.parentMessageId) }
              : {}),
            ...(asString(candidate.revisionRootMessageId)
              ? { revisionRootMessageId: asString(candidate.revisionRootMessageId) }
              : {}),
            ...(asString(candidate.supersedesMessageId)
              ? { supersedesMessageId: asString(candidate.supersedesMessageId) }
              : {}),
            ...(asString(candidate.runtimeSegmentId)
              ? { runtimeSegmentId: asString(candidate.runtimeSegmentId) }
              : {})
          }
        ]
      })
    : []
  const runtimeSegments = Array.isArray(value.runtimeSegments)
    ? value.runtimeSegments.flatMap((candidate): PersistedRuntimeSegment[] => {
        if (!isRecord(candidate)) return []
        const id = asString(candidate.id)
        const agentFrameId = asString(candidate.agentFrameId)
        const frameworkId = asString(candidate.frameworkId)
        const startedAt = asNumber(candidate.startedAt)
        if (!id || !agentFrameId || !frameworkId || startedAt === undefined) {
          return []
        }
        return [
          {
            id,
            agentFrameId,
            frameworkId,
            startedAt,
            ...(asString(candidate.providerId)
              ? { providerId: asString(candidate.providerId) }
              : {}),
            ...(asString(candidate.backendId) ? { backendId: asString(candidate.backendId) } : {}),
            ...(asString(candidate.agentName) ? { agentName: asString(candidate.agentName) } : {}),
            ...(asString(candidate.model) ? { model: asString(candidate.model) } : {}),
            ...(asNumber(candidate.endedAt) !== undefined
              ? { endedAt: asNumber(candidate.endedAt) }
              : {})
          }
        ]
      })
    : []
  const activities = Array.isArray(value.activities)
    ? value.activities.flatMap((candidate): PersistedBranchActivity[] => {
        if (!isRecord(candidate)) return []
        const activity = sanitizeToolActivity(candidate)
        const agentFrameId = asString(candidate.agentFrameId)
        const messageBranchId = asString(candidate.messageBranchId)
        const promptMessageId = asString(candidate.promptMessageId)
        const runtimeSegmentId = asString(candidate.runtimeSegmentId)
        return activity && agentFrameId && messageBranchId && promptMessageId && runtimeSegmentId
          ? [
              {
                ...activity,
                agentFrameId,
                messageBranchId,
                promptMessageId,
                runtimeSegmentId
              }
            ]
          : []
      })
    : []
  const activityGroups = Array.isArray(value.activityGroups)
    ? value.activityGroups.flatMap((candidate): PersistedBranchActivityGroup[] => {
        if (!isRecord(candidate)) return []
        const group = sanitizeActivityGroup(candidate)
        const agentFrameId = asString(candidate.agentFrameId)
        const messageBranchId = asString(candidate.messageBranchId)
        const promptMessageId = asString(candidate.promptMessageId)
        return group && agentFrameId && messageBranchId && promptMessageId
          ? [
              {
                ...(options.preserveRuntimeState
                  ? group
                  : normalizeActivityGroupAfterRestore(group)),
                agentFrameId,
                messageBranchId,
                promptMessageId
              }
            ]
          : []
      })
    : []
  const graph: PersistedConversationGraph = {
    schemaVersion: 1,
    rootFrameId,
    activeFrameId,
    frames,
    branches,
    messages,
    activities,
    activityGroups,
    runtimeSegments
  }
  try {
    validateConversationGraph(graph)
    return materializeNestedDelegateActivities(graph)
  } catch {
    return undefined
  }
}

export type ConversationGraphMaterializationPhase = 'create' | 'messages' | 'activities'

export class ConversationGraphMaterializationError extends Error {
  readonly phase: ConversationGraphMaterializationPhase
  override readonly cause: unknown

  constructor(phase: ConversationGraphMaterializationPhase, cause: unknown) {
    super('Conversation graph materialization failed.')
    this.name = 'ConversationGraphMaterializationError'
    this.phase = phase
    this.cause = cause
  }
}

const materializeGraphPhase = <Result>(
  phase: ConversationGraphMaterializationPhase,
  operation: () => Result
): Result => {
  try {
    return operation()
  } catch (error) {
    throw new ConversationGraphMaterializationError(phase, error)
  }
}

const projectActiveNestedDelegateActivities = (
  graph: PersistedConversationGraph
): PersistedToolActivity[] => {
  const activeMessageIds = new Set(resolveActiveConversationMessages(graph).map(({ id }) => id))
  return graph.activities.flatMap(
    ({ agentFrameId, messageBranchId, runtimeSegmentId, ...activity }) => {
      void agentFrameId
      void messageBranchId
      void runtimeSegmentId
      return parseNestedDelegateInvocationId(activity.id) !== undefined &&
        activeMessageIds.has(activity.promptMessageId)
        ? [activity]
        : []
    }
  )
}

export const materializeSessionConversationGraph = (
  session: PersistedChatSession
): MaterializedPersistedChatSession => {
  const messageGraph = session.conversationGraph
    ? materializeGraphPhase('messages', () =>
        synchronizeActiveConversationMessages(
          session.conversationGraph!,
          session.messages,
          session.updatedAt
        )
      )
    : materializeGraphPhase('create', () =>
        createLinearConversationGraph({
          sessionId: session.id,
          messages: session.messages,
          frameworkId: session.agentFrameworkId,
          providerId: session.agentConfiguration?.providerId,
          backendId: session.agentBackendId,
          model: session.agentModel,
          createdAt: session.createdAt,
          updatedAt: session.updatedAt
        })
      )
  const graph = materializeGraphPhase('activities', () =>
    materializeNestedDelegateActivities(
      synchronizeActiveConversationActivities(
        messageGraph,
        session.activities ?? [],
        session.activityGroups ?? []
      )
    )
  )
  const nestedDelegateActivities = projectActiveNestedDelegateActivities(graph)
  const activityIds = new Set((session.activities ?? []).map(({ id }) => id))
  return {
    ...session,
    conversationGraph: graph,
    messages: resolveActiveConversationMessages(graph).map(projectConversationMessage),
    activities: [
      ...(session.activities ?? []),
      ...nestedDelegateActivities.filter(({ id }) => !activityIds.has(id))
    ]
  }
}

// Keeps the active run pointer only when both its message id and timestamp are valid.
const sanitizeActiveRun = (activeRun: unknown): PersistedActiveRun | undefined => {
  if (!isRecord(activeRun)) return undefined

  const promptMessageId = asString(activeRun.promptMessageId)
  const startedAt = asNumber(activeRun.startedAt)

  return promptMessageId && startedAt !== undefined ? { promptMessageId, startedAt } : undefined
}

const sanitizeSessionResumeRecovery = (
  recovery: unknown
): PersistedSessionResumeRecovery | undefined => {
  if (!isRecord(recovery) || recovery.kind !== 'resume-required') return undefined
  if (
    recovery.cause !== 'app-restart' &&
    recovery.cause !== 'cancelled' &&
    recovery.cause !== 'connection-lost'
  ) {
    return undefined
  }
  const promptMessageId = asString(recovery.promptMessageId)
  return {
    kind: 'resume-required',
    cause: recovery.cause,
    ...(promptMessageId ? { promptMessageId } : {})
  }
}

const sanitizePendingHistoryReplay = (
  replay: unknown
): PersistedPendingHistoryReplay | undefined => {
  if (!isRecord(replay)) return undefined
  if (replay.kind === 'all') return { kind: 'all' }
  if (replay.kind !== 'before-message') return undefined
  const messageId = asString(replay.messageId)
  return messageId ? { kind: 'before-message', messageId } : undefined
}

const sanitizeSessionBranchSource = (value: unknown): PersistedSessionBranchSource | undefined => {
  if (
    !isRecord(value) ||
    !hasOnlyFields(value, ['sessionId', 'agentFrameId', 'messageBranchId', 'headMessageId'])
  ) {
    return undefined
  }

  const sessionId = asString(value.sessionId)
  const agentFrameId = asString(value.agentFrameId)
  const messageBranchId = asString(value.messageBranchId)
  const headMessageId = asString(value.headMessageId)
  if (
    !sessionId ||
    (value.agentFrameId !== undefined && !agentFrameId) ||
    (value.messageBranchId !== undefined && !messageBranchId) ||
    (value.headMessageId !== undefined && !headMessageId)
  ) {
    return undefined
  }

  return {
    sessionId,
    ...(agentFrameId ? { agentFrameId } : {}),
    ...(messageBranchId ? { messageBranchId } : {}),
    ...(headMessageId ? { headMessageId } : {})
  }
}

const sanitizeSessionAgentConfiguration = (
  value: unknown
): SessionAgentConfiguration | undefined => {
  if (!isRecord(value) || !hasOnlyFields(value, ['providerId', 'model', 'reasoningEffort'])) {
    return undefined
  }
  const providerId = asString(value.providerId)
  const model = asString(value.model)
  if (!providerId || !isReasoningEffort(value.reasoningEffort)) return undefined
  if (value.model !== undefined && !model) return undefined
  return {
    providerId,
    ...(model ? { model } : {}),
    reasoningEffort: value.reasoningEffort
  }
}

// Rebuilds a persisted chat session and normalizes any runtime-only interrupted state.
const sanitizeSession = (
  session: unknown,
  options: { preserveLegacyUploadPaths?: boolean; preserveRuntimeState?: boolean } = {}
): PersistedChatSession | undefined => {
  if (!isRecord(session)) return undefined

  const id = asString(session.id)

  if (!id) return undefined

  const artifacts = Array.isArray(session.artifacts)
    ? session.artifacts.map(sanitizeArtifact).filter((item): item is PersistedArtifact => !!item)
    : []
  const activities = Array.isArray(session.activities)
    ? session.activities
        .map(sanitizeToolActivity)
        .filter((item): item is PersistedToolActivity => !!item)
    : []
  const activityGroups = Array.isArray(session.activityGroups)
    ? session.activityGroups
        .map(sanitizeActivityGroup)
        .filter((item): item is PersistedActivityGroup => !!item)
        .map((group) =>
          options.preserveRuntimeState ? group : normalizeActivityGroupAfterRestore(group)
        )
    : []
  const revision = asNumber(session.revision)
  const number = asNumber(session.number)
  let sanitized: PersistedChatSession = {
    id,
    ...(Number.isSafeInteger(number) && (number ?? 0) > 0 ? { number } : {}),
    // Content value is a hint; the repository overrides it with the session file's directory on load.
    projectId: asString(session.projectId) ?? '',
    revision: Number.isSafeInteger(revision) && (revision ?? -1) >= 0 ? revision : 0,
    title: asString(session.title) ?? id,
    cwd: asString(session.cwd) ?? '',
    status: asSessionStatus(session.status),
    permissionProfile:
      session.permissionProfile === undefined
        ? DEFAULT_PERMISSION_PROFILE
        : normalizePermissionProfile(session.permissionProfile),
    // Auto-review defaults off: a missing or non-boolean value restores as disabled, and only an
    // explicit true turns it on.
    autoReviewEnabled: session.autoReviewEnabled === true ? true : false,
    // Memory predates its per-conversation switch, so historical or malformed values retain the
    // previous enabled behavior. Only an explicit false opts this Session out.
    memoryEnabled: session.memoryEnabled === false ? false : true,
    // Only deny changes behavior; missing/malformed historical values preserve delegation.
    delegationPolicy: normalizeDelegationPolicy(session.delegationPolicy),
    messages: Array.isArray(session.messages)
      ? session.messages
          .map((message) => sanitizeMessage(message, options))
          .filter((item): item is PersistedChatMessage => !!item)
      : [],
    createdAt: asNumber(session.createdAt) ?? 0,
    updatedAt: asNumber(session.updatedAt) ?? 0
  }
  const activeRun = sanitizeActiveRun(session.activeRun)
  const taskRunCommitId = asString(session.taskRunCommitId)
  const resumeRecovery = sanitizeSessionResumeRecovery(session.resumeRecovery)
  const branchSource = sanitizeSessionBranchSource(session.branchSource)
  const pendingHistoryReplay =
    sanitizePendingHistoryReplay(session.pendingHistoryReplay) ??
    // Migrate feature-preview files that used the cutoff id as a top-level scalar.
    (() => {
      const messageId = asString(session.pendingHistoryReplayBeforeMessageId)
      return messageId ? ({ kind: 'before-message', messageId } as const) : undefined
    })()
  const error = asString(session.error)
  const agentFrameworkId = asString(session.agentFrameworkId) as AgentFrameworkId | undefined
  const agentBackendId = asString(session.agentBackendId)
  const providerSessionId = asString(session.providerSessionId)
  const providerContinuityToken = asString(session.providerContinuityToken)
  const agentModel = asString(session.agentModel)
  const agentConfiguration = sanitizeSessionAgentConfiguration(session.agentConfiguration)
  const description = asString(session.description)
  const sessionDetailsSource =
    session.sessionDetailsSource === 'fallback' ||
    session.sessionDetailsSource === 'generated' ||
    session.sessionDetailsSource === 'manual'
      ? session.sessionDetailsSource
      : undefined
  const sessionDetailsGeneration = sanitizeSessionDetailsGeneration(
    session.sessionDetailsGeneration
  )
  const enabledComputeHosts = Array.isArray(session.enabledComputeHosts)
    ? session.enabledComputeHosts.filter(
        (item): item is string => typeof item === 'string' && item.startsWith('ssh:')
      )
    : []
  const hasSelectedComputeHosts = Object.prototype.hasOwnProperty.call(
    session,
    'selectedComputeHosts'
  )
  const selectedComputeHostCandidates = hasSelectedComputeHosts
    ? Array.isArray(session.selectedComputeHosts)
      ? session.selectedComputeHosts.filter(
          (item): item is string => typeof item === 'string' && item.startsWith('ssh:')
        )
      : []
    : enabledComputeHosts
  const enabledComputeHostSet = new Set(enabledComputeHosts)
  const selectedComputeHosts = selectedComputeHostCandidates.filter((providerId) =>
    enabledComputeHostSet.has(providerId)
  )
  const computeConcurrencyLimit = asNumber(session.computeConcurrencyLimit)
  if (
    session.computeConcurrencyLimit !== undefined &&
    (!Number.isInteger(computeConcurrencyLimit) ||
      (computeConcurrencyLimit ?? 0) < 1 ||
      (computeConcurrencyLimit ?? 0) > 500)
  ) {
    return undefined
  }

  if (activeRun) sanitized.activeRun = activeRun
  if (taskRunCommitId) sanitized.taskRunCommitId = taskRunCommitId
  if (resumeRecovery) sanitized.resumeRecovery = resumeRecovery
  if (branchSource) sanitized.branchSource = branchSource
  if (pendingHistoryReplay) sanitized.pendingHistoryReplay = pendingHistoryReplay
  if (error) sanitized.error = error
  // Only meaningful alongside an error; persisted only when explicitly false (absent = reportable).
  if (error && session.errorReportable === false) sanitized.errorReportable = false
  const artifactErrorEventIds = [...new Set(asStringArray(session.artifactErrorEventIds))]
  if (error?.startsWith('Generated file finalization') && artifactErrorEventIds.length > 0) {
    sanitized.artifactErrorEventIds = artifactErrorEventIds
  }
  if (agentFrameworkId && AGENT_FRAMEWORK_IDS.has(agentFrameworkId)) {
    sanitized.agentFrameworkId = agentFrameworkId
  }
  if (agentBackendId) sanitized.agentBackendId = agentBackendId
  if (providerSessionId) sanitized.providerSessionId = providerSessionId
  if (providerContinuityToken) sanitized.providerContinuityToken = providerContinuityToken
  if (agentModel) sanitized.agentModel = agentModel
  if (agentConfiguration) sanitized.agentConfiguration = agentConfiguration
  if (description !== undefined && description.length <= SESSION_DETAILS_DESCRIPTION_MAX_LENGTH) {
    sanitized.description = description
  }
  if (sessionDetailsSource) sanitized.sessionDetailsSource = sessionDetailsSource
  // Restore the pin only from an explicit true so malformed or legacy files stay unpinned.
  if (session.pinned === true) sanitized.pinned = true
  const archivedAt = asNumber(session.archivedAt)
  if (archivedAt !== undefined && Number.isSafeInteger(archivedAt) && archivedAt > 0) {
    sanitized.archivedAt = archivedAt
  }
  if (artifacts.length > 0) sanitized.artifacts = artifacts
  const filesRevision = asNumber(session.filesRevision)
  if (filesRevision !== undefined && Number.isInteger(filesRevision) && filesRevision >= 0) {
    sanitized.filesRevision = filesRevision
  }
  if (activities.length > 0) sanitized.activities = activities
  if (activityGroups.length > 0) sanitized.activityGroups = activityGroups
  if (enabledComputeHosts.length > 0) sanitized.enabledComputeHosts = enabledComputeHosts
  if (hasSelectedComputeHosts || enabledComputeHosts.length > 0) {
    sanitized.selectedComputeHosts = selectedComputeHosts
  }
  if (computeConcurrencyLimit !== undefined) {
    sanitized.computeConcurrencyLimit = computeConcurrencyLimit
  }
  // Specialist ID: accept any non-empty string. The main process validates it against SpecialistService
  // at send time; the sanitizer only ensures the value is safe to re-persist.
  const specialistId = asString(session.specialistId)
  if (specialistId) sanitized.specialistId = specialistId
  // Pending is a fail-closed marker: only the explicit true value survives sanitization. Historical
  // files omit it and retain the pre-marker behavior (their desired binding is considered applied).
  if (session.specialistBindingPending === true) sanitized.specialistBindingPending = true
  const contextUsage = sanitizeAcpContextUsage(session.contextUsage)
  if (contextUsage) sanitized.contextUsage = contextUsage
  const runtimeContext = sanitizeSessionRuntimeContext(session.runtimeContext)
  if (runtimeContext) sanitized.runtimeContext = runtimeContext
  const planHistoryProjections = sanitizePlanHistoryProjections(session.planHistoryProjections)
  if (planHistoryProjections) sanitized.planHistoryProjections = planHistoryProjections
  if (
    sanitized.status === 'waiting-plan-approval' &&
    runtimeContext?.plan?.approval !== 'pending'
  ) {
    // Approval waiting is meaningful only with a restorable pending Plan. A corrupt or settled
    // context must not leave the conversation permanently blocked with nothing to approve.
    sanitized.status = 'idle'
    sanitized.activeRun = undefined
  }
  if (
    sanitized.status === 'waiting-for-user' &&
    !activities.some(
      (activity) => activity.elicitation?.state === 'pending' && activity.elicitation.durable
    )
  ) {
    // A user-input wait is restorable only while its durable question remains actionable.
    sanitized.status = 'idle'
    sanitized.activeRun = undefined
  }

  // Normalize before graph creation so a legacy flat transcript never seeds a streaming message or
  // loses the active prompt identity while activeRun is cleared.
  if (!options.preserveRuntimeState) {
    sanitized = normalizeSessionAfterRestore(sanitized, { deferPermissionValidation: true })
  }

  if (session.conversationGraph !== undefined) {
    const graph = sanitizeConversationGraph(session.conversationGraph, options)
    if (!graph) return undefined
    const nestedDelegateActivities = projectActiveNestedDelegateActivities(graph)
    const activityIds = new Set((sanitized.activities ?? []).map(({ id }) => id))
    sanitized.conversationGraph = graph
    sanitized.messages = resolveActiveConversationMessages(graph).map(projectConversationMessage)
    sanitized.activities = [
      ...(sanitized.activities ?? []),
      ...nestedDelegateActivities.filter(({ id }) => !activityIds.has(id))
    ]
  } else {
    sanitized.conversationGraph = createLinearConversationGraph({
      sessionId: sanitized.id,
      messages: sanitized.messages,
      frameworkId: sanitized.agentFrameworkId,
      providerId: sanitized.agentConfiguration?.providerId,
      backendId: sanitized.agentBackendId,
      model: sanitized.agentModel,
      createdAt: sanitized.createdAt,
      updatedAt: sanitized.updatedAt
    })
  }

  const canonicalGraph = sanitized.conversationGraph
  // Call IDs are Session-scoped keys; drop every colliding Turn's detail rather than choose one.
  const modelCallIdCounts = new Map<string, number>()
  for (const message of canonicalGraph.messages) {
    for (const call of message.modelCallUsage ?? []) {
      modelCallIdCounts.set(call.id, (modelCallIdCounts.get(call.id) ?? 0) + 1)
    }
  }
  sanitized.conversationGraph = {
    ...canonicalGraph,
    messages: canonicalGraph.messages.map((message) =>
      message.modelCallUsage?.some((call) => (modelCallIdCounts.get(call.id) ?? 0) > 1)
        ? { ...message, modelCallUsage: undefined }
        : message
    )
  }
  sanitized.messages = resolveActiveConversationMessages(sanitized.conversationGraph).map(
    projectConversationMessage
  )

  const firstSessionDetailsMessageId = sanitized.messages.find(
    (message) => isHumanUserMessage(message) && !isHiddenControlMessage(message)
  )?.id
  if (
    sessionDetailsGeneration &&
    !branchSource &&
    sessionDetailsGeneration.sourceMessageId === firstSessionDetailsMessageId
  ) {
    sanitized.sessionDetailsGeneration = sessionDetailsGeneration
  }
  if (
    session.sessionDetailsGenerationEligible === true &&
    !branchSource &&
    session.sessionDetailsGeneration === undefined
  ) {
    sanitized.sessionDetailsGenerationEligible = true
  }

  // Normalize only after resolving the canonical active Branch. Recovery references and the durable
  // interrupted marker must never be inferred from an abandoned Branch.
  if (!options.preserveRuntimeState) {
    sanitized = normalizeSessionAfterRestore(sanitized, { reconcileCompletedRecovery: true })
  }
  if (!options.preserveRuntimeState) {
    const permissionAuthority = resolveRestorablePermissionToolAuthority(sanitized)
    sanitized = {
      ...sanitized,
      ...(sanitized.activities
        ? {
            activities: sanitized.activities.map((activity) =>
              normalizeActivityAfterRestore(activity, permissionAuthority)
            )
          }
        : {}),
      ...(sanitized.conversationGraph
        ? {
            conversationGraph: {
              ...sanitized.conversationGraph,
              activities: sanitized.conversationGraph.activities.map((activity) => ({
                ...activity,
                ...normalizeActivityAfterRestore(activity, permissionAuthority)
              }))
            }
          }
        : {})
    }
  }
  const activeUserMessageIds = new Set(
    sanitized.messages.filter((message) => message.role === 'user').map((message) => message.id)
  )
  if (
    sanitized.resumeRecovery?.promptMessageId &&
    !activeUserMessageIds.has(sanitized.resumeRecovery.promptMessageId)
  ) {
    sanitized.resumeRecovery = {
      kind: 'resume-required',
      cause: sanitized.resumeRecovery.cause
    }
  }
  if (
    sanitized.pendingHistoryReplay?.kind === 'before-message' &&
    !activeUserMessageIds.has(sanitized.pendingHistoryReplay.messageId)
  ) {
    sanitized.pendingHistoryReplay = undefined
  }
  const recoveryPromptMessageId = sanitized.resumeRecovery?.promptMessageId
  if (recoveryPromptMessageId && sanitized.conversationGraph) {
    sanitized.conversationGraph = {
      ...sanitized.conversationGraph,
      messages: sanitized.conversationGraph.messages.map((message) =>
        message.id === recoveryPromptMessageId && message.role === 'user'
          ? { ...message, interrupted: true }
          : message
      )
    }
  }

  return sanitizeSessionMessageImages(sanitized)
}

