const sanitizeDelegatedWorkRecords = (value: unknown): DelegatedWorkRecord[] | undefined => {
  if (!Array.isArray(value)) return undefined
  const frameIds = new Set<string>()
  const attemptIds = new Set<string>()
  const records: DelegatedWorkRecord[] = []
  for (const rawRecord of value) {
    if (
      !isRecord(rawRecord) ||
      !hasOnlyFields(rawRecord, ['agentFrameId', 'attempts']) ||
      !Array.isArray(rawRecord.attempts) ||
      rawRecord.attempts.length === 0
    ) {
      return undefined
    }
    const agentFrameId = asString(rawRecord.agentFrameId)
    if (!agentFrameId || frameIds.has(agentFrameId)) return undefined
    frameIds.add(agentFrameId)
    const attempts: DelegatedWorkAttemptRecord[] = []
    let runningCount = 0
    for (const rawAttempt of rawRecord.attempts) {
      if (
        !isRecord(rawAttempt) ||
        !hasOnlyFields(rawAttempt, [
          'id',
          'initiatingTurnMessageId',
          'status',
          'resolvedAgent',
          'executionModel',
          'runtimeSegmentIds',
          'startedAt',
          'endedAt',
          'terminalMessageId',
          'cancellationReason',
          'error'
        ])
      ) {
        return undefined
      }
      const id = asString(rawAttempt.id)
      const initiatingTurnMessageId =
        rawAttempt.initiatingTurnMessageId === undefined
          ? undefined
          : asString(rawAttempt.initiatingTurnMessageId)
      const status = asString(rawAttempt.status) as DelegatedWorkAttemptStatus | undefined
      const resolvedAgent = sanitizeDelegatedWorkResolvedAgent(rawAttempt.resolvedAgent)
      const executionModel =
        rawAttempt.executionModel === undefined
          ? undefined
          : sanitizeResolvedSubagentModelSnapshot(rawAttempt.executionModel)
      const startedAt = asNumber(rawAttempt.startedAt)
      const runtimeSegmentIds = asStringArray(rawAttempt.runtimeSegmentIds)
      if (
        !id ||
        (rawAttempt.initiatingTurnMessageId !== undefined && !initiatingTurnMessageId) ||
        attemptIds.has(id) ||
        !status ||
        !DELEGATED_WORK_ATTEMPT_STATUSES.has(status) ||
        !resolvedAgent ||
        (rawAttempt.executionModel !== undefined && !executionModel) ||
        startedAt === undefined ||
        startedAt < 0 ||
        !Array.isArray(rawAttempt.runtimeSegmentIds) ||
        runtimeSegmentIds.length !== rawAttempt.runtimeSegmentIds.length ||
        new Set(runtimeSegmentIds).size !== runtimeSegmentIds.length
      ) {
        return undefined
      }
      attemptIds.add(id)
      const endedAt = rawAttempt.endedAt === undefined ? undefined : asNumber(rawAttempt.endedAt)
      const terminalMessageId =
        rawAttempt.terminalMessageId === undefined
          ? undefined
          : asString(rawAttempt.terminalMessageId)
      const cancellationReason =
        rawAttempt.cancellationReason === undefined
          ? undefined
          : (asString(rawAttempt.cancellationReason) as DelegatedWorkCancellationReason | undefined)
      let error: { code: string; message: string } | undefined
      if (rawAttempt.error !== undefined) {
        if (!isRecord(rawAttempt.error) || !hasOnlyFields(rawAttempt.error, ['code', 'message'])) {
          return undefined
        }
        const code = asString(rawAttempt.error.code)
        const message = asString(rawAttempt.error.message)
        if (!code || !message) return undefined
        error = { code, message }
      }
      if (status === 'running') {
        runningCount += 1
        if (
          endedAt !== undefined ||
          terminalMessageId !== undefined ||
          cancellationReason !== undefined ||
          error !== undefined
        ) {
          return undefined
        }
      } else if (endedAt === undefined || endedAt < startedAt) {
        return undefined
      }
      if (status === 'completed' && terminalMessageId === undefined) return undefined
      if (
        (status === 'cancelled') !== (cancellationReason !== undefined) ||
        (cancellationReason && !DELEGATED_WORK_CANCELLATION_REASONS.has(cancellationReason)) ||
        (status === 'error') !== (error !== undefined)
      ) {
        return undefined
      }
      attempts.push({
        id,
        ...(initiatingTurnMessageId ? { initiatingTurnMessageId } : {}),
        status,
        resolvedAgent,
        ...(executionModel ? { executionModel } : {}),
        runtimeSegmentIds,
        startedAt,
        ...(endedAt !== undefined ? { endedAt } : {}),
        ...(terminalMessageId ? { terminalMessageId } : {}),
        ...(cancellationReason ? { cancellationReason } : {}),
        ...(error ? { error } : {})
      })
    }
    if (runningCount > 1 || (runningCount === 1 && attempts.at(-1)?.status !== 'running')) {
      return undefined
    }
    records.push({ agentFrameId, attempts })
  }
  return records
}

const sanitizeSessionDelegatedWorkRuntimeContext = (
  value: unknown
): SessionDelegatedWorkRuntimeContext | undefined => {
  if (
    !isRecord(value) ||
    !hasOnlyFields(value, [
      'records',
      'recordsQuarantine',
      'messageCommands',
      'messageCommandsQuarantine',
      'questionRequests',
      'questionRequestsQuarantine'
    ]) ||
    (value.messageCommands !== undefined && !Array.isArray(value.messageCommands)) ||
    (value.questionRequests !== undefined && !Array.isArray(value.questionRequests))
  ) {
    return undefined
  }
  const sanitizedRecords = sanitizeDelegatedWorkRecords(value.records)
  const records = sanitizedRecords ?? []
  const recordsQuarantine =
    sanitizedRecords === undefined
      ? value.recordsQuarantine === undefined
        ? structuredClone(value.records)
        : {
            // Both payloads remain opaque. The envelope only prevents a later corrupt generation
            // from replacing an earlier quarantine; neither generation becomes read-model records.
            previous: structuredClone(value.recordsQuarantine),
            current: structuredClone(value.records)
          }
      : value.recordsQuarantine === undefined
        ? undefined
        : structuredClone(value.recordsQuarantine)
  const messageCommands: DelegatedMessageCommand[] = []
  const isolatedQuestionOwner = (): Pick<
    SessionDelegatedWorkRuntimeContext,
    'questionRequests' | 'questionRequestsQuarantine'
  > => {
    const isolated = sanitizeSessionDelegatedWorkRuntimeContext({
      records: value.records,
      ...(value.questionRequests === undefined ? {} : { questionRequests: value.questionRequests }),
      ...(value.questionRequestsQuarantine === undefined
        ? {}
        : { questionRequestsQuarantine: value.questionRequestsQuarantine })
    })
    return {
      ...(isolated?.questionRequests === undefined
        ? {}
        : { questionRequests: isolated.questionRequests }),
      ...(isolated?.questionRequestsQuarantine === undefined
        ? {}
        : { questionRequestsQuarantine: isolated.questionRequestsQuarantine })
    }
  }
  if (value.messageCommandsQuarantine !== undefined) {
    return {
      records,
      ...(recordsQuarantine === undefined ? {} : { recordsQuarantine }),
      messageCommandsQuarantine: structuredClone(value.messageCommandsQuarantine),
      ...isolatedQuestionOwner()
    }
  }
  const quarantine = (): SessionDelegatedWorkRuntimeContext => ({
    records,
    ...(recordsQuarantine === undefined ? {} : { recordsQuarantine }),
    messageCommandsQuarantine: structuredClone(value.messageCommands),
    ...isolatedQuestionOwner()
  })
  const commandIds = new Set<string>()
  const commandKeys = new Set<string>()
  for (const raw of (value.messageCommands ?? []) as unknown[]) {
    if (
      !isRecord(raw) ||
      !hasOnlyFields(raw, [
        'messageId',
        'requestId',
        'sourcePrincipal',
        'canonicalDigest',
        'sourceFrameId',
        'sourceAttemptId',
        'targetFrameId',
        'targetAttemptId',
        'continuationAttemptId',
        'rootPromptMessageId',
        'rootOriginMessageId',
        'callerRootMessageId',
        'rootBranchId',
        'rootBranchRevision',
        'direction',
        'disposition',
        'text',
        'kind',
        'replyToMessageId',
        'retryOfMessageId',
        'laneSequence',
        'queuedAt',
        'receipt'
      ]) ||
      !isRecord(raw.receipt)
    )
      return quarantine()
    const required = [
      'messageId',
      'requestId',
      'sourcePrincipal',
      'canonicalDigest',
      'sourceFrameId',
      'targetFrameId',
      'rootOriginMessageId',
      'callerRootMessageId',
      'rootBranchId',
      'rootBranchRevision',
      'direction',
      'disposition',
      'text',
      'kind'
    ].map((key) => asString(raw[key]))
    if (required.some((part) => !part)) return quarantine()
    const [messageId, requestId, sourcePrincipal] = required as string[]
    const laneSequence = asNumber(raw.laneSequence)
    const queuedAt = asNumber(raw.queuedAt)
    const status = asString(raw.receipt.status)
    const identity = `${sourcePrincipal}\u0000${requestId}`
    const optionalStringFields = [
      'sourceAttemptId',
      'targetAttemptId',
      'continuationAttemptId',
      'rootPromptMessageId',
      'replyToMessageId',
      'retryOfMessageId'
    ]
    const optionalStringsValid = optionalStringFields.every(
      (field) => raw[field] === undefined || Boolean(asString(raw[field]))
    )
    const toParent = raw.direction === 'to_parent' && raw.disposition === 'message'
    const toRunningChild = raw.direction === 'to_child' && raw.disposition === 'message'
    const toContinuedChild = raw.direction === 'to_child' && raw.disposition === 'continued'
    const routeValid =
      (toParent &&
        Boolean(asString(raw.sourceAttemptId)) &&
        Boolean(asString(raw.rootPromptMessageId)) &&
        raw.targetAttemptId === undefined &&
        raw.continuationAttemptId === undefined) ||
      (toRunningChild &&
        Boolean(asString(raw.targetAttemptId)) &&
        raw.sourceAttemptId === undefined &&
        raw.rootPromptMessageId === undefined &&
        raw.continuationAttemptId === undefined) ||
      (toContinuedChild &&
        Boolean(asString(raw.continuationAttemptId)) &&
        raw.sourceAttemptId === undefined &&
        raw.rootPromptMessageId === undefined &&
        raw.targetAttemptId === undefined)
    const receiptValid =
      (status === 'queued' &&
        hasOnlyFields(raw.receipt, ['status', 'dispatchStartedAt', 'dispatchEpoch']) &&
        (raw.receipt.dispatchStartedAt === undefined ||
          (asNumber(raw.receipt.dispatchStartedAt) !== undefined &&
            asNumber(raw.receipt.dispatchStartedAt)! >= queuedAt!)) &&
        (raw.receipt.dispatchEpoch === undefined || Boolean(asString(raw.receipt.dispatchEpoch))) &&
        (raw.receipt.dispatchStartedAt === undefined) ===
          (raw.receipt.dispatchEpoch === undefined)) ||
      (status === 'accepted' &&
        hasOnlyFields(raw.receipt, ['status', 'acceptedAt', 'evidence']) &&
        asNumber(raw.receipt.acceptedAt) !== undefined &&
        asNumber(raw.receipt.acceptedAt)! >= queuedAt! &&
        ['provider_prompt_accepted', 'provider_prompt_completed'].includes(
          String(raw.receipt.evidence)
        )) ||
      (status === 'failed' &&
        hasOnlyFields(raw.receipt, ['status', 'failedAt', 'error']) &&
        asNumber(raw.receipt.failedAt) !== undefined &&
        asNumber(raw.receipt.failedAt)! >= queuedAt! &&
        isRecord(raw.receipt.error) &&
        hasOnlyFields(raw.receipt.error, ['code', 'message', 'retryable']) &&
        Boolean(asString(raw.receipt.error.code)) &&
        Boolean(asString(raw.receipt.error.message)) &&
        typeof raw.receipt.error.retryable === 'boolean') ||
      (status === 'uncertain' &&
        hasOnlyFields(raw.receipt, ['status', 'uncertainAt', 'resolution']) &&
        asNumber(raw.receipt.uncertainAt) !== undefined &&
        asNumber(raw.receipt.uncertainAt)! >= queuedAt! &&
        ['pending', 'acknowledged'].includes(String(raw.receipt.resolution)))
    if (
      commandIds.has(messageId) ||
      commandKeys.has(identity) ||
      laneSequence === undefined ||
      !Number.isSafeInteger(laneSequence) ||
      laneSequence < 1 ||
      queuedAt === undefined ||
      queuedAt < 0 ||
      !/^[a-f0-9]{64}$/.test(String(raw.canonicalDigest)) ||
      !optionalStringsValid ||
      !routeValid ||
      !['info', 'question'].includes(String(raw.kind)) ||
      !receiptValid
    )
      return quarantine()
    commandIds.add(messageId)
    commandKeys.add(identity)
    messageCommands.push(structuredClone(raw) as DelegatedMessageCommand)
  }
  const messageOwner = {
    records,
    ...(recordsQuarantine === undefined ? {} : { recordsQuarantine }),
    ...(value.messageCommands === undefined ? {} : { messageCommands })
  }
  const sanitizeAnswers = (
    raw: unknown,
    questionCount: number
  ): DelegatedQuestionAnswer[] | undefined => {
    if (!Array.isArray(raw) || raw.length > questionCount) return undefined
    const answers = raw.flatMap((answer): DelegatedQuestionAnswer[] => {
      if (!isRecord(answer) || !hasOnlyFields(answer, ['questionIndex', 'value'])) return []
      const questionIndex = asNumber(answer.questionIndex)
      const answerValue = asString(answer.value)
      return questionIndex !== undefined &&
        Number.isSafeInteger(questionIndex) &&
        questionIndex >= 0 &&
        questionIndex < questionCount &&
        answerValue &&
        answerValue.length <= 4_000
        ? [{ questionIndex, value: answerValue }]
        : []
    })
    return answers.length === raw.length &&
      new Set(answers.map((answer) => answer.questionIndex)).size === answers.length
      ? answers
      : undefined
  }
  const sanitizeQuestionRequests = (
    rawRequests: unknown
  ): DelegatedQuestionRequest[] | undefined => {
    if (!Array.isArray(rawRequests)) return undefined
    const questionRequests: DelegatedQuestionRequest[] = []
    const questionIds = new Set<string>()
    for (const raw of rawRequests as unknown[]) {
      if (
        !isRecord(raw) ||
        !hasOnlyFields(raw, [
          'requestId',
          'canonicalDigest',
          'sourceFrameId',
          'sourceAttemptId',
          'sourceRuntimeSegmentId',
          'sourceMessageBranchId',
          'rootOriginMessageId',
          'rootBranchId',
          'sourceName',
          'questions',
          'sequence',
          'askedAt',
          'status',
          'draftAnswers',
          'draftQuestionIndex',
          'answers',
          'respondedAt',
          'continuationAttemptId',
          'failure'
        ])
      ) {
        return undefined
      }
      const required = [
        'requestId',
        'canonicalDigest',
        'sourceFrameId',
        'sourceAttemptId',
        'sourceRuntimeSegmentId',
        'sourceMessageBranchId',
        'rootOriginMessageId',
        'rootBranchId',
        'sourceName'
      ].map((field) => asString(raw[field]))
      if (required.some((part) => !part)) return undefined
      const [requestId] = required as string[]
      const questions = sanitizeAgentUserChoiceRequest({
        sessionId: 'delegated-question',
        questions: raw.questions
      })?.questions
      const sequence = asNumber(raw.sequence)
      const askedAt = asNumber(raw.askedAt)
      const draftQuestionIndex = asNumber(raw.draftQuestionIndex)
      const status = asString(raw.status)
      const draftAnswers = questions && sanitizeAnswers(raw.draftAnswers, questions.length)
      const answers =
        raw.answers === undefined || !questions
          ? undefined
          : sanitizeAnswers(raw.answers, questions.length)
      const respondedAt = raw.respondedAt === undefined ? undefined : asNumber(raw.respondedAt)
      const continuationAttemptId =
        raw.continuationAttemptId === undefined ? undefined : asString(raw.continuationAttemptId)
      let failure: { code: string; message: string } | undefined
      if (raw.failure !== undefined) {
        if (!isRecord(raw.failure) || !hasOnlyFields(raw.failure, ['code', 'message'])) {
          return undefined
        }
        const code = asString(raw.failure.code)
        const message = asString(raw.failure.message)
        if (!code || !message) return undefined
        failure = { code, message }
      }
      if (
        questionIds.has(requestId) ||
        !/^[a-f0-9]{64}$/.test(String(raw.canonicalDigest)) ||
        !questions ||
        (raw.sequence !== undefined &&
          (sequence === undefined || !Number.isSafeInteger(sequence) || sequence < 1)) ||
        askedAt === undefined ||
        askedAt < 0 ||
        !['pending', 'confirmed', 'cancelled', 'failed'].includes(String(status)) ||
        !draftAnswers ||
        draftQuestionIndex === undefined ||
        !Number.isSafeInteger(draftQuestionIndex) ||
        draftQuestionIndex < 0 ||
        draftQuestionIndex >= questions.length ||
        (raw.answers !== undefined && !answers) ||
        (raw.respondedAt !== undefined && (respondedAt === undefined || respondedAt < askedAt)) ||
        (raw.continuationAttemptId !== undefined && !continuationAttemptId) ||
        (status === 'pending' &&
          (answers !== undefined ||
            respondedAt !== undefined ||
            continuationAttemptId !== undefined ||
            failure !== undefined)) ||
        (status === 'confirmed' &&
          (!answers ||
            answers.length !== questions.length ||
            respondedAt === undefined ||
            !continuationAttemptId ||
            failure !== undefined)) ||
        ((status === 'cancelled' || status === 'failed') &&
          (respondedAt === undefined || !failure || continuationAttemptId !== undefined))
      ) {
        return undefined
      }
      questionIds.add(requestId)
      questionRequests.push(structuredClone(raw) as DelegatedQuestionRequest)
    }
    return questionRequests
  }
  if (value.questionRequestsQuarantine !== undefined) {
    if (value.questionRequests !== undefined) {
      return {
        ...messageOwner,
        questionRequestsQuarantine: {
          active: structuredClone(value.questionRequests),
          quarantine: structuredClone(value.questionRequestsQuarantine)
        }
      }
    }
    const recovered = sanitizeQuestionRequests(value.questionRequestsQuarantine)
    return recovered
      ? { ...messageOwner, questionRequests: recovered }
      : {
          ...messageOwner,
          questionRequestsQuarantine: structuredClone(value.questionRequestsQuarantine)
        }
  }
  if (value.questionRequests === undefined) return messageOwner
  const questionRequests = sanitizeQuestionRequests(value.questionRequests)
  if (!questionRequests) {
    return {
      ...messageOwner,
      questionRequestsQuarantine: structuredClone(value.questionRequests)
    }
  }
  return {
    ...messageOwner,
    questionRequests
  }
}
const PERMISSION_FINGERPRINT_PATTERN = /^[a-f0-9]{64}$/
const PDF_CONTEXT_CHECKSUM_PATTERN = /^[a-f0-9]{64}$/

const sanitizeSessionPdfBinding = (value: unknown): SessionPdfBinding | undefined => {
  if (!isRecord(value) || value.version !== 1) return undefined
  const bindingId = asString(value.bindingId)
  const sourceKind = asString(value.sourceKind)
  const sourceFileId = asString(value.sourceFileId)
  const sourceVersionId = asString(value.sourceVersionId)
  const sourceSessionId = asString(value.sourceSessionId)
  const name = asString(value.name)
  const sizeBytes = asNumber(value.sizeBytes)
  const checksum = asString(value.checksum)
  const linkedAt = asNumber(value.linkedAt)
  if (
    !bindingId ||
    bindingId.length > 512 ||
    (sourceKind !== 'artifact-version' && sourceKind !== 'upload-version') ||
    !sourceFileId ||
    sourceFileId.length > 512 ||
    !sourceVersionId ||
    sourceVersionId.length > 512 ||
    !sourceSessionId ||
    sourceSessionId.length > 512 ||
    !name ||
    name.length > 4096 ||
    value.mimeType !== 'application/pdf' ||
    sizeBytes === undefined ||
    !Number.isSafeInteger(sizeBytes) ||
    sizeBytes < 0 ||
    !checksum ||
    !PDF_CONTEXT_CHECKSUM_PATTERN.test(checksum) ||
    linkedAt === undefined ||
    !Number.isSafeInteger(linkedAt) ||
    linkedAt < 0
  ) {
    return undefined
  }
  return {
    version: 1,
    bindingId,
    sourceKind,
    sourceFileId,
    sourceVersionId,
    sourceSessionId,
    name,
    mimeType: 'application/pdf',
    sizeBytes,
    checksum,
    linkedAt
  }
}

export const sanitizeSessionPdfContext = (value: unknown): SessionPdfContext | undefined => {
  if (
    !isRecord(value) ||
    value.version !== 1 ||
    !Array.isArray(value.bindings) ||
    value.bindings.length < 1 ||
    value.bindings.length > MAX_SESSION_PDF_CONTEXTS
  ) {
    return undefined
  }
  const bindings = value.bindings.map(sanitizeSessionPdfBinding)
  if (bindings.some((binding) => binding === undefined)) return undefined
  const validBindings = bindings as SessionPdfBinding[]
  const identities = validBindings.map(
    ({ sourceKind, sourceVersionId }) => `${sourceKind}:${sourceVersionId}`
  )
  if (
    new Set(validBindings.map(({ bindingId }) => bindingId)).size !== validBindings.length ||
    new Set(identities).size !== identities.length
  ) {
    return undefined
  }
  return { version: 1, bindings: validBindings }
}

export const sanitizeMessagePdfContextSnapshot = (
  value: unknown
): MessagePdfContextSnapshot | undefined => {
  const context = sanitizeSessionPdfContext(value)
  if (!context || !isRecord(value)) return context
  const activeBindingId = asString(value.activeBindingId)
  if (
    !activeBindingId ||
    !context.bindings.some(({ bindingId }) => bindingId === activeBindingId)
  ) {
    return context
  }
  if (value.readingPosition === undefined) return { ...context, activeBindingId }
  if (!isRecord(value.readingPosition)) return context
  const pageNumber = asNumber(value.readingPosition.pageNumber)
  const pageCount = asNumber(value.readingPosition.pageCount)
  if (
    pageNumber === undefined ||
    pageCount === undefined ||
    !Number.isSafeInteger(pageNumber) ||
    !Number.isSafeInteger(pageCount) ||
    pageNumber < 1 ||
    pageCount < pageNumber
  ) {
    return { ...context, activeBindingId }
  }
  return { ...context, activeBindingId, readingPosition: { pageNumber, pageCount } }
}
const PERMISSION_SCOPES = new Set(['once', 'session', 'project', 'global'])
const PERMISSION_OPTION_KINDS = new Set([
  'allow_once',
  'allow_always',
  'reject_once',
  'reject_always'
])
const PERMISSION_CAPABILITY_KIND_SET = new Set<string>(PERMISSION_CAPABILITY_KINDS)
const MAX_PERMISSION_CONTEXT_STRING_CHARS = 16_000
const MAX_PERMISSION_CONTEXT_RAW_CHARS = 8_000

const boundedPermissionString = (value: unknown): string | undefined => {
  const text = asString(value)
  return text && text.length <= MAX_PERMISSION_CONTEXT_STRING_CHARS ? text : undefined
}

const sanitizePermissionRawInput = (value: unknown): unknown | undefined => {
  if (value === null) return null
  return sanitizeRawToolPayload(value, MAX_PERMISSION_CONTEXT_RAW_CHARS)
}

const sanitizePermissionCapability = (value: unknown): PermissionCapability | undefined => {
  if (!isRecord(value)) return undefined
  const kind = asString(value.kind)
  const key = boundedPermissionString(value.key)?.trim()
  if (!kind || !PERMISSION_CAPABILITY_KIND_SET.has(kind) || !key) return undefined

  if (value.qualifier === undefined) {
    return { kind: kind as PermissionCapability['kind'], key }
  }
  if (!isRecord(value.qualifier)) return undefined
  const mode = asString(value.qualifier.mode)
  if (mode === 'any') {
    return { kind: kind as PermissionCapability['kind'], key, qualifier: { mode } }
  }
  const qualifierValue = boundedPermissionString(value.qualifier.value)?.trim()
  if (
    (mode !== 'category' && mode !== 'exact') ||
    !qualifierValue ||
    (mode === 'exact' && !EXACT_PERMISSION_QUALIFIER_PATTERN.test(qualifierValue))
  ) {
    return undefined
  }
  return {
    kind: kind as PermissionCapability['kind'],
    key,
    qualifier: { mode, value: qualifierValue }
  }
}

const sanitizePermissionRequest = (value: unknown): AcpPermissionRequest | undefined => {
  if (!isRecord(value)) return undefined
  const requestId = boundedPermissionString(value.requestId)
  const sessionId = boundedPermissionString(value.sessionId)
  const toolCallId = boundedPermissionString(value.toolCallId)
  const rawTitle = boundedPermissionString(value.title)
  const title = rawTitle ? sanitizeToolDetailText(rawTitle) : undefined
  if (!requestId || !sessionId || !toolCallId || !title || !Array.isArray(value.options)) {
    return undefined
  }

  const optionIds = new Set<string>()
  const options = value.options.flatMap((candidate) => {
    if (!isRecord(candidate)) return []
    const optionId = boundedPermissionString(candidate.optionId)
    const name = boundedPermissionString(candidate.name)
    const kind = boundedPermissionString(candidate.kind)
    const scope = asString(candidate.scope)
    const normalizedKind = kind?.toLowerCase()
    if (
      !optionId ||
      !name ||
      !kind ||
      !normalizedKind ||
      !PERMISSION_OPTION_KINDS.has(normalizedKind) ||
      optionIds.has(optionId) ||
      (scope !== undefined && !PERMISSION_SCOPES.has(scope)) ||
      (scope === 'once' && normalizedKind !== 'allow_once') ||
      ((scope === 'session' || scope === 'project' || scope === 'global') &&
        normalizedKind !== 'allow_always')
    ) {
      return []
    }
    optionIds.add(optionId)
    return [
      {
        optionId,
        name,
        kind,
        ...(scope
          ? { scope: scope as NonNullable<AcpPermissionRequest['options'][number]['scope']> }
          : {})
      }
    ]
  })
  if (options.length === 0 || options.length !== value.options.length || options.length > 32) {
    return undefined
  }

  const request: AcpPermissionRequest = { requestId, sessionId, toolCallId, title, options }
  const status = boundedPermissionString(value.status)
  const providerToolName = boundedPermissionString(value.providerToolName)
  const mcpIdentity = boundedPermissionString(value.mcpIdentity)
  const toolKind = boundedPermissionString(value.toolKind)
  const commandPrefix = Array.isArray(value.commandPrefix)
    ? value.commandPrefix.map(boundedPermissionString).filter((item): item is string => !!item)
    : undefined
  const toolLocations = Array.isArray(value.toolLocations)
    ? value.toolLocations.flatMap((candidate) => {
        if (!isRecord(candidate)) return []
        const path = boundedPermissionString(candidate.path)
        const line = asNumber(candidate.line)
        if (!path || (line !== undefined && (!Number.isSafeInteger(line) || line < 0))) return []
        return [{ path, ...(line === undefined ? {} : { line }) }]
      })
    : undefined
  const rawInput = sanitizePermissionRawInput(value.rawInput)
  if (value.rawInput !== undefined && rawInput === undefined) return undefined
  if (
    value.toolLocations !== undefined &&
    (!Array.isArray(value.toolLocations) ||
      toolLocations?.length !== value.toolLocations.length ||
      toolLocations.length > 100)
  ) {
    return undefined
  }
  if (
    value.commandPrefix !== undefined &&
    (!Array.isArray(value.commandPrefix) ||
      commandPrefix?.length !== value.commandPrefix.length ||
      commandPrefix.length > 32)
  ) {
    return undefined
  }

  if (status) request.status = status
  if (providerToolName) request.providerToolName = providerToolName
  if (typeof value.isMcp === 'boolean') request.isMcp = value.isMcp
  if (mcpIdentity) request.mcpIdentity = mcpIdentity
  if (toolKind) request.toolKind = toolKind as AcpPermissionRequest['toolKind']
  if (toolLocations) {
    request.toolLocations = toolLocations as AcpPermissionRequest['toolLocations']
  }
  if (commandPrefix) request.commandPrefix = commandPrefix
  if (rawInput !== undefined) request.rawInput = rawInput
  return request
}

export const sanitizeSessionPermissionRuntimeContext = (
  value: unknown
): SessionPermissionRuntimeContext | undefined => {
  if (!isRecord(value)) return undefined
  if (
    Object.keys(value).some(
      (field) =>
        ![
          'request',
          'state',
          'originatingPromptMessageId',
          'fingerprint',
          'categoryKey',
          'capability',
          'createdAt'
        ].includes(field)
    )
  ) {
    return undefined
  }
  const request = sanitizePermissionRequest(value.request)
  const state = value.state === undefined ? 'pending' : asString(value.state)
  const originatingPromptMessageId = boundedPermissionString(value.originatingPromptMessageId)
  const fingerprint = asString(value.fingerprint)
  const categoryKey = boundedPermissionString(value.categoryKey)
  const capability = sanitizePermissionCapability(value.capability)
  const createdAt = asNumber(value.createdAt)
  if (
    !request ||
    (state !== 'pending' && state !== 'continuing') ||
    !originatingPromptMessageId ||
    !fingerprint ||
    !PERMISSION_FINGERPRINT_PATTERN.test(fingerprint) ||
    createdAt === undefined ||
    !Number.isSafeInteger(createdAt) ||
    createdAt < 0 ||
    (value.capability !== undefined && !capability)
  ) {
    return undefined
  }
  return {
    state,
    request,
    originatingPromptMessageId,
    fingerprint,
    ...(categoryKey ? { categoryKey } : {}),
    ...(capability ? { capability } : {}),
    createdAt
  }
}

export const sanitizeSessionRuntimeContext = (
  value: unknown
): SessionRuntimeContext | undefined => {
  if (!isRecord(value) || value.version !== 1) return undefined
  const revision = asNumber(value.revision)
  if (revision === undefined || !Number.isSafeInteger(revision) || revision < 0) return undefined

  const result: {
    version: 1
    revision: number
    plan?: SessionPlanRuntimeContext
    delegatedWork?: SessionDelegatedWorkRuntimeContext
    permission?: SessionPermissionRuntimeContext
    pdfContext?: SessionPdfContext
    sideChat?: PersistedSideChat
    sideChatRelays?: readonly PersistedSideChatRelay[]
  } = {
    version: 1,
    revision
  }
  let legacyRelays: readonly PersistedSideChatRelay[] = []
  let directRelays: readonly PersistedSideChatRelay[] = []
  const budget = { remaining: 2_000 }
  for (const [owner, ownerValue] of Object.entries(value)) {
    if (owner === 'version' || owner === 'revision') continue
    if (
      owner === 'plan' ||
      owner === 'delegatedWork' ||
      owner === 'permission' ||
      owner === 'pdfContext'
    ) {
      const sanitizedJson = sanitizeRuntimeContextValue(ownerValue, budget)
      if (sanitizedJson === undefined) return undefined
      if (owner === 'pdfContext') {
        const pdfContext = sanitizeSessionPdfContext(sanitizedJson)
        if (!pdfContext) return undefined
        result.pdfContext = pdfContext
      } else if (owner === 'plan') {
        const plan = sanitizeSessionPlanRuntimeContext(sanitizedJson)
        if (!plan) return undefined
        result.plan = plan
      } else if (owner === 'permission') {
        const permission = sanitizeSessionPermissionRuntimeContext(sanitizedJson)
        if (!permission) return undefined
        result.permission = permission
      } else {
        const delegatedWork = sanitizeSessionDelegatedWorkRuntimeContext(sanitizedJson)
        if (!delegatedWork) return undefined
        result.delegatedWork = delegatedWork
      }
      continue
    }
    if (owner === 'sideChat') {
      const sanitized = sanitizePersistedSideChatWithLegacyRelays(ownerValue)
      if (sanitized) {
        result.sideChat = sanitized.sideChat
        legacyRelays = sanitized.legacyRelays
      }
      continue
    }
    if (owner === 'sideChatRelays') {
      if (!Array.isArray(ownerValue) || ownerValue.length > MAX_SIDE_CHAT_RELAYS) continue
      const relays = ownerValue.map((relay) => sanitizePersistedSideChatRelay(relay))
      if (relays.some((relay) => relay === undefined)) continue
      directRelays = relays as PersistedSideChatRelay[]
      continue
    }
    return undefined
  }
  const sideChatRelays = [...directRelays, ...legacyRelays]
  if (sideChatRelays.length > MAX_SIDE_CHAT_RELAYS) return undefined
  const relayIds = new Set<string>()
  for (const relay of sideChatRelays) {
    if (relayIds.has(relay.id)) return undefined
    relayIds.add(relay.id)
  }
  if (sideChatRelays.length > 0) result.sideChatRelays = sideChatRelays
  return result
}

// Historical projections are presentation-only snapshots. Rebuild all derived fields from the
// validated Plan document and statuses so persisted JSON cannot manufacture lifecycle state or
// inconsistent counters. A prompt binding is mandatory because unbound history cannot be isolated
// safely across Message Branches.
const sanitizeHistoricalPlanProjection = (
  value: unknown
): { projection: ActivePlanProjection; jsonChars: number } | undefined => {
  const sanitizedJson = sanitizeRuntimeContextValue(value, { remaining: 10_000 })
  if (!isRecord(sanitizedJson)) return undefined
  const jsonChars = JSON.stringify(sanitizedJson).length
  if (jsonChars > MAX_PLAN_HISTORY_PROJECTION_JSON_CHARS) return undefined

  const originatingPromptMessageId = asString(sanitizedJson.originatingPromptMessageId)
  const revision = asNumber(sanitizedJson.revision)
  const lifecycle = asString(sanitizedJson.lifecycle)
  if (
    !originatingPromptMessageId ||
    revision === undefined ||
    !Number.isSafeInteger(revision) ||
    revision < 0 ||
    !lifecycle ||
    (!PLAN_LIFECYCLES.has(lifecycle as PlanLifecycle) && lifecycle !== 'interrupted')
  ) {
    return undefined
  }

  const runtimePlan = sanitizeSessionPlanRuntimeContext({
    artifactId: sanitizedJson.artifactId,
    artifactVersionId: sanitizedJson.artifactVersionId,
    artifactChecksum: sanitizedJson.artifactChecksum,
    originatingPromptMessageId,
    approval: sanitizedJson.approval,
    stepStatuses: sanitizedJson.stepStatuses
  })
  if (!runtimePlan) return undefined

  let document
  try {
    document = parsePlanDocumentV1(sanitizedJson.document)
  } catch {
    return undefined
  }
  const titles = planStepTitles(document)
  return {
    jsonChars,
    projection: {
      artifactId: runtimePlan.artifactId,
      artifactVersionId: runtimePlan.artifactVersionId,
      artifactChecksum: runtimePlan.artifactChecksum,
      originatingPromptMessageId,
      revision,
      approval: runtimePlan.approval,
      lifecycle: derivePlanLifecycle(document, runtimePlan.approval, runtimePlan.stepStatuses),
      document,
      stepStatuses: runtimePlan.stepStatuses,
      stepStates: projectPlanStepStates(document, runtimePlan.stepStatuses),
      counts: {
        phases: document.phases.length,
        delegations: document.phases.reduce((sum, phase) => sum + phase.delegations.length, 0),
        steps: titles.length,
        completed: titles.filter((title) => {
          const status = runtimePlan.stepStatuses[title]?.status
          return status === 'completed' || status === 'skipped'
        }).length,
        inProgress: titles.filter((title) => {
          const status = runtimePlan.stepStatuses[title]?.status
          return status === 'in_progress'
        }).length
      }
    }
  }
}

export const sanitizePlanHistoryProjections = (
  value: unknown
): ActivePlanProjection[] | undefined => {
  if (!Array.isArray(value)) return undefined
  let remainingPlanHistoryChars = MAX_PLAN_HISTORY_JSON_CHARS
  const projections: ActivePlanProjection[] = []
  for (const candidate of value.slice(-MAX_PLAN_HISTORY_PROJECTIONS).toReversed()) {
    const sanitizedProjection = sanitizeHistoricalPlanProjection(candidate)
    if (!sanitizedProjection) continue
    if (sanitizedProjection.jsonChars > remainingPlanHistoryChars) break
    remainingPlanHistoryChars -= sanitizedProjection.jsonChars
    projections.unshift(sanitizedProjection.projection)
  }
  return projections.length > 0 ? projections : undefined
}

