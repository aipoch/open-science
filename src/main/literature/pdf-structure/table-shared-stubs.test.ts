it('retains a wrapped count unit across two category rows', () => {
  const t = refineTable(countRaw, countTokens, [], [], countRules)
  expect(t.cells).toContainEqual(
    expect.objectContaining({ text: 'Ethnicity (N)', column: 0, rowSpan: 2 })
  )
  expect(
    t.grid.filter((r: string[]) => /Hispanic/.test(r[1])).map((r: string[]) => r.slice(1))
  ).toEqual([
    ['Hispanic or Latino', '10', '0', '10'],
    ['Not Hispanic or Latino', '10', '15', '25']
  ])
})
it('does not merge an independent parenthesized label or a ruled separation', () => {
  const other = countTokens.map((t) =>
    t.text === 'N' && t.rect[1] > 150 ? { ...t, text: 'Group' } : t
  )
  expect(refineTable(countRaw, other, [], [], countRules).cells).not.toContainEqual(
    expect.objectContaining({ text: 'Ethnicity (Group)', rowSpan: 2 })
  )
  const split = [0, 151, 90, 151]
  expect(
    refineTable(countRaw, countTokens, [], [], [...countRules, split]).cells
  ).not.toContainEqual(expect.objectContaining({ text: 'Ethnicity (N)', rowSpan: 2 }))
})
it('keeps a grade/time label and comparison shared by all consecutive grades', () => {
  const t = refineTable(gradeRaw, gradeTokens, [], [], gradeRules)
  expect(t.cells).toContainEqual(
    expect.objectContaining({
      text: 'NCI CTCAE grade at 4 weeks of HFS treatment',
      column: 0,
      rowSpan: 4
    })
  )
  expect(t.cells).toContainEqual(expect.objectContaining({ text: '0.005', column: 4, rowSpan: 4 }))
  expect(t.grid.slice(1, 5).map((r: string[]) => r.slice(1, 4))).toEqual([
    ['None', '7', '2'],
    ['1', '22', '10'],
    ['2', '25', '32'],
    ['3', '6', '16']
  ])
  expect(t.grid.at(-1)).toEqual(['Effectiveness rate', '', '48/60 (80%)', '31/60 (51.7%)', '0.001'])
})
it('does not infer a shared grade label when the sequence or counts are incomplete', () => {
  for (const [from, to] of [
    ['None', 'Unknown'],
    ['7', 'Missing'],
    ['treatment', 'Independent']
  ]) {
    const changed = gradeTokens.map((t) => (t.text === from ? { ...t, text: to } : t))
    expect(refineTable(gradeRaw, changed, [], [], gradeRules).repairs).not.toContain(
      'graded-stub-span-recovered'
    )
  }
})
