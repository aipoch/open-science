"""Regenerate bundled schemas using the engine's real MCP tool discovery (no network)."""
import asyncio
import json
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'resources' / 'medical-data'))
from core import PROVIDERS, Store
from server import create_server
from access import POLICIES


def compact(value):
    if isinstance(value, dict):
        return {key: compact(item) for key, item in value.items() if key != 'title'}
    if isinstance(value, list):
        return [compact(item) for item in value]
    return value


def example(name, schema):
    values = {'path': 'incoming/source.csv', 'table_name': 'dataset', 'sql': 'SELECT count(*) FROM dataset',
              'job_id': '0' * 32, 'query': 'TP53', 'url': 'https://www.ebi.ac.uk/',
              'filename': 'source.csv', 'directory_url': 'https://physionet.org/files/mimic-iv-demo/2.2/',
              'field': 'symbol', 'value': 'TP53', 'cycle_begin_year': 2017, 'accession': 'CVCL_0030',
              'input_type': 'Gene Symbol', 'output_type': 'Gene ID', 'output_taxon': 10090,
              'markers': {'D5S818': '12,13'}}
    result = {}
    for key in schema.get('required', []):
        spec = schema['properties'][key]
        result[key] = values.get(key, {'integer': 1, 'number': 1, 'string': 'TP53', 'array': ['TP53'], 'object': {}, 'boolean': False}.get(spec.get('type'), 'TP53'))
    return result


async def main():
    methods, routes, providers = {}, [], []
    with tempfile.TemporaryDirectory(prefix='medical-schemas-') as directory:
        for provider, config in PROVIDERS.items():
            store = Store(provider, Path(directory))
            try:
                tools = await create_server(store).list_tools()
                policy = POLICIES.get(provider)
                providers.append({'id': provider, 'label': config['label'], 'access': config['access'],
                                  'docs': config['docs'], 'portal': config['portal'], 'download': config['download'],
                                  'notes': config['notes'], 'hosts': config['hosts'],
                                  'credentialNames': policy[3] if policy else [],
                                  'accessKind': policy[0] if policy else 'public',
                                  'applicationUrl': policy[2] if policy else config['docs']})
                for tool in tools:
                    description = (tool.description or '').split('\nAccess:')[0]
                    method = {'description': description, 'input': compact(tool.inputSchema), 'exampleArgs': example(tool.name, tool.inputSchema)}
                    if tool.name in methods and methods[tool.name] != method:
                        raise ValueError(f'Provider-specific schema mismatch: {tool.name}')
                    methods[tool.name] = method
                    routes.append({'provider': provider, 'method': tool.name})
            finally:
                store.executor.shutdown(wait=True)
    text = '''// Generated by scripts/generate-medical-data-tools.py from real MCP discovery.
import type { ToolDescriptor } from '@aipoch/connector-core'

export type MedicalProvider = {
  id: string; label: string; access: string; docs: string; portal: string
  download: boolean; notes: string; hosts: string[]; credentialNames: string[]
  accessKind: string; applicationUrl: string
}
export const MEDICAL_PROVIDERS: MedicalProvider[] = ''' + json.dumps(providers, ensure_ascii=False, indent=2) + '''

type MedicalMethod = { description: string; input: Record<string, unknown>; exampleArgs: Record<string, unknown> }
const methods: Record<string, MedicalMethod> = ''' + json.dumps(methods, ensure_ascii=False, indent=2) + '''

export const MEDICAL_ROUTES: { provider: string; method: string }[] = ''' + json.dumps(routes, indent=2) + '''

// Host-owned handlers dispatch to the bundled, provider-scoped data engine after authorization.
// The independent package never launches processes, resolves credentials or chooses storage.
export const MEDICAL_DATA_TOOLS: ToolDescriptor[] = MEDICAL_ROUTES.map(({ provider, method }) => ({
  id: method,
  connector: provider,
  credentialKeys: [],
  ...methods[method],
  required: (methods[method].input.required as string[] | undefined) ?? [],
  returns: 'Provider-scoped JSON. Downloads, imports and extraction return {job_id,status,next_tool}; poll get_job until ready/error. query_local returns bounded metadata and a local CSV path; patient rows remain local. provider_info documents formats, paths, access and limits. Errors are not empty data.',
  run: async () => { throw new Error('This tool requires the bundled medical data engine host handler.') }
}))
'''
    (ROOT / 'packages/connector-builtins/src/medical-data.ts').write_text(text, encoding='utf-8')
    print(json.dumps({'providers': len(providers), 'methods': len(methods), 'routes': len(routes)}))


asyncio.run(main())
